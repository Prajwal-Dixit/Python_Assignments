def Addition(value1, value2):
    Result = value1 + value2
    return Result

def Subtraction(value1, value2):
    Result = value1 - value2
    return Result

def Multiplication(value1, value2):
    Result = value1 * value2
    return Result

def Division(value1, value2):
    Result = value1 / value2
    return Result
